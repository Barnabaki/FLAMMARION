"""Derive the app's assets from the pulled source data in data/source/.  Run: python3 scripts/build_app_assets.py
Needs: numpy, pillow, tifffile, imagecodecs.  Outputs are committed, so the app itself needs no Python.

  data/source/dem/jezero_dem_clipped_fullcrater.tif  ->  public/data/terrain/jezero_dem_40m.png (+ .json)   terrain mesh (RGB-encoded)
                                                     ->  src/lib/demRoute.js                                native 20 m crop around the route
  data/source/weather/weather_historic.json          ->  src/lib/weatherTable.js                            mean diurnal cycle per LTST hour
"""
import json, os
import numpy as np, tifffile
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
P = lambda *a: os.path.join(ROOT, *a)
os.makedirs(P('public/data/terrain'), exist_ok=True)

# ---------------------------------------------------------------- DEM
FULL = dict(west=77.10, south=17.95, east=78.05, north=18.85)          # bbox of the full-crater GeoTIFF (build_dem.py)
dem = tifffile.imread(P('data/source/dem/jezero_dem_clipped_fullcrater.tif')).astype(np.float64)   # rows north -> south
H, W = dem.shape
assert not np.isnan(dem).any()
SRC = dict(source_product='M20_JezeroCrater_CTXDEM_20m.tif', source_pds_lid='urn:nasa:pds:mars2020_ctx_basemap_2021:data:m20_ctxdem_mosaic',
           vertical_datum='elevation of the source DEM (MOLA areoid)', units='m')
# 40 m mesh grid: 2x2 block mean, stored as an 8-bit RGB PNG (browsers decode it losslessly): value = R*256 + G = (elev_m + 3000) * 10
h2, w2 = H // 2, W // 2
g = dem[:h2 * 2, :w2 * 2].reshape(h2, 2, w2, 2).mean(axis=(1, 3))
bbox40 = dict(west=FULL['west'], north=FULL['north'], east=FULL['west'] + (FULL['east'] - FULL['west']) * (w2 * 2) / W,
              south=FULL['north'] - (FULL['north'] - FULL['south']) * (h2 * 2) / H)
v = np.round((g + 3000) * 10).astype(np.uint16)
Image.fromarray(np.dstack([(v >> 8).astype(np.uint8), (v & 255).astype(np.uint8), np.zeros(v.shape, np.uint8)]), 'RGB').save(P('public/data/terrain/jezero_dem_40m.png'), optimize=True)
json.dump(dict(**SRC, **bbox40, width=w2, height=h2, encoding='RGB PNG, elev_m = (R * 256 + G) / 10 - 3000', row_order='north_to_south',
               cell='value[r][c] is the mean over the cell whose NW corner is (north - r*dlat, west + c*dlon)',
               min_elev_m=round(float(g.min()), 1), max_elev_m=round(float(g.max()), 1)), open(P('public/data/terrain/jezero_dem_40m.json'), 'w'), indent=1)
# native 20 m crop around the route, as a JS module (decimetres, integers)
RB = dict(west=77.39, south=18.425, east=77.48, north=18.49)
dlon, dlat = (FULL['east'] - FULL['west']) / W, (FULL['north'] - FULL['south']) / H
c0, c1 = int((RB['west'] - FULL['west']) / dlon), int(np.ceil((RB['east'] - FULL['west']) / dlon))
r0, r1 = int((FULL['north'] - RB['north']) / dlat), int(np.ceil((FULL['north'] - RB['south']) / dlat))
crop = dem[r0:r1, c0:c1]
meta = dict(**SRC, west=FULL['west'] + c0 * dlon, east=FULL['west'] + c1 * dlon, north=FULL['north'] - r0 * dlat, south=FULL['north'] - r1 * dlat,
            width=crop.shape[1], height=crop.shape[0], cell_m=20, row_order='north_to_south', unit='decimetres')
open(P('src/lib/demRoute.js'), 'w').write(
    '// GENERATED by scripts/build_app_assets.py from the Mars 2020 CTX DEM mosaic (20 m). Do not edit.\n'
    f'export const DEM_ROUTE = {json.dumps(meta)};\n'
    f'DEM_ROUTE.data = Int32Array.from({json.dumps(np.round(crop * 10).astype(int).ravel().tolist(), separators=(",", ":"))});\n')

# ---------------------------------------------------------------- weather
recs = json.load(open(P('data/source/weather/weather_historic.json')))
KEYS = dict(air_temp_c='ambient_temp_c', ground_temp_c='ground_temp_c', pressure_pa='pressure_pa', wind_ms='wind_speed_ms', uv_wm2='uv_250_400nm_wm2')
def table(prefix, site, bundle):
    rs = [r for r in recs if r['source_instrument'].startswith(prefix)]
    out = dict(site=site, instrument=rs[0]['source_instrument'], pds=bundle, sols=sorted({r['sol'] for r in rs}), binning='mean of hourly means per LTST hour bin [h, h+1)')
    for k, src in KEYS.items():
        mean, n, lo, hi = [], [], [], []
        for h in range(24):
            v = [r[src] for r in rs if int(r['ltst'][:2]) == h and r.get(src) is not None]
            mean.append(round(float(np.mean(v)), 2) if v else None); n.append(len(v))
            lo.append(round(min(v), 2) if v else None); hi.append(round(max(v), 2) if v else None)
        if any(x is not None for x in mean): out[k] = mean; out[k + '_n_sols'] = n; out[k + '_min'] = lo; out[k + '_max'] = hi
    return out
meda = table('MEDA', 'Jezero crater (Perseverance)', 'urn:nasa:pds:mars2020_meda')
rems = table('REMS', 'Gale crater (Curiosity) — NOT Jezero', 'MSLREM_1001 (MODRDR)')
assert all(v is not None for k in ('air_temp_c', 'ground_temp_c', 'pressure_pa', 'wind_ms') for v in meda[k])
open(P('src/lib/weatherTable.js'), 'w').write(
    '// GENERATED by scripts/build_app_assets.py from data/source/weather/weather_historic.json (NASA PDS). Do not edit.\n'
    f'export const MEDA_TABLE = {json.dumps(meda)};\nexport const REMS_TABLE = {json.dumps(rems)};\n')

print('40 m grid', g.shape, bbox40, '| route crop', crop.shape, round(crop.min(), 1), round(crop.max(), 1))
print('MEDA sols', meda['sols'], 'wind n per hour', meda['wind_ms_n_sols']); print('REMS sols', rems['sols'])
